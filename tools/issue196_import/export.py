#!/usr/bin/env python3
"""Re-capture the three Issue 196 buildings from a read-only Workshop snapshot."""
import argparse
import json
from pathlib import Path
import shutil
import sqlite3
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
HELPER = Path(__file__).resolve().parent
BUILDINGS = [
    {"id": "farm", "min": {"x": 100, "y": 8, "z": 470}, "max": {"x": 108, "y": 15, "z": 476},
     "path": "schematics/outskirts/farm.mts"},
    {"id": "shepherd_hut", "min": {"x": 135, "y": 8, "z": 470}, "max": {"x": 143, "y": 16, "z": 477},
     "path": "schematics/outskirts/small_house.mts"},
    {"id": "demo_house", "min": {"x": 170, "y": 8, "z": 470}, "max": {"x": 178, "y": 15, "z": 476},
     "path": "schematics/demo_house.mts"},
]


def lua(value):
    if isinstance(value, dict):
        return "{" + ",".join("[" + lua(k) + "]=" + lua(v) for k, v in value.items()) + "}"
    if isinstance(value, list):
        return "{" + ",".join(lua(v) for v in value) + "}"
    if isinstance(value, str):
        return '"' + "".join("\\" + str(ord(c)).zfill(3) if ord(c) < 32 else "\\" + c if c in '\\\"' else c for c in value) + '"'
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return "nil"
    return str(value)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--world", type=Path, required=True)
    parser.add_argument("--engine", default="/Applications/luanti.app/Contents/MacOS/luanti")
    parser.add_argument("--port", type=int, default=39490)
    args = parser.parse_args()
    source = args.world.resolve()
    work = Path(tempfile.mkdtemp(prefix="towns-issue196-export-"))
    for name in ("world.mt", "map_meta.txt"):
        shutil.copy2(source / name, work / name)
    with sqlite3.connect((source / "map.sqlite").as_uri() + "?mode=ro", uri=True) as src:
        with sqlite3.connect(work / "map.sqlite") as dst:
            src.backup(dst)
    (work / "issue196-buildings.json").write_text(json.dumps(BUILDINGS))
    out = work / "out"
    out.mkdir()
    mod = work / "worldmods/issue196_export"
    mod.mkdir(parents=True)
    shutil.copy2(HELPER / "export.lua", mod / "init.lua")
    (mod / "mod.conf").write_text("name = issue196_export\n")
    (work / "export.conf").write_text("enable_ipv6 = false\nbind_address = 127.0.0.1\nserver_announce = false\n")
    with (work / "stdout.log").open("w") as log:
        process = subprocess.run([args.engine, "--server", "--world", str(work), "--gameid", "mineclone2",
                                  "--config", str(work / "export.conf"), "--port", str(args.port),
                                  "--logfile", str(work / "engine.log")], stdout=log,
                                 stderr=subprocess.STDOUT, timeout=180)
    result = work / "issue196-results.json"
    if process.returncode or not result.exists():
        raise SystemExit("Capture failed; inspect " + str(work / "engine.log"))
    records = json.loads(result.read_text())
    if {r["id"] for r in records} != {b["id"] for b in BUILDINGS}:
        raise SystemExit("Capture report is incomplete: " + str(work))
    for building in BUILDINGS:
        shutil.copy2(work / "out" / (building["id"] + ".mts"), ROOT / building["path"])
    by_id = {r["id"]: r for r in records}
    for building in BUILDINGS:
        record = by_id[building["id"]]
        sidecar = {"metadata": record["metadata"] or [], "required_nodes": record["required_nodes"]}
        path = ROOT / building["path"].replace(".mts", ".lua")
        path.write_text("-- Generated by tools/issue196_import/export.py.\nreturn " + lua(sidecar) + "\n")
    print("Re-captured farm, shepherd_hut and demo_house from read-only Workshop snapshot:", work)


if __name__ == "__main__":
    main()
