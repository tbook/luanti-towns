#!/usr/bin/env python3
"""Export edited templates using a read-only SQLite snapshot and Luanti."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import sqlite3
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
HELPER = Path(__file__).resolve().parent


def lua(value):
    if isinstance(value, dict):
        return '{' + ','.join('[' + lua(k) + ']=' + lua(v) for k, v in value.items()) + '}'
    if isinstance(value, list):
        return '{' + ','.join(lua(v) for v in value) + '}'
    if isinstance(value, str):
        # Lua 5.1 needs decimal escapes for control characters, not JSON \u escapes.
        return '"' + ''.join('\\' + str(ord(c)).zfill(3) if ord(c) < 32 else '\\' + c if c in '\\"' else c for c in value) + '"'
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if value is None:
        return 'nil'
    return str(value)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--world', type=Path, required=True)
    parser.add_argument('--engine', default='/Applications/luanti.app/Contents/MacOS/luanti')
    parser.add_argument('--port', type=int, default=39487)
    parser.add_argument('--only', nargs='+', metavar='ID', help='Re-export only these buildings, preserving other templates')
    parser.add_argument('--validate', action='store_true', help='Also check runtime placement, entrances and inventories at all four rotations')
    args = parser.parse_args()
    source = args.world.resolve()
    work = Path(tempfile.mkdtemp(prefix='towns-workshop-export-'))
    for name in ('world.mt', 'map_meta.txt'):
        shutil.copy2(source / name, work / name)
    with sqlite3.connect((source / 'map.sqlite').as_uri() + '?mode=ro', uri=True) as src:
        with sqlite3.connect(work / 'map.sqlite') as dst:
            src.backup(dst)
    snapshot_sha = hashlib.sha256((work / 'map.sqlite').read_bytes()).hexdigest()
    config = json.loads((HELPER / 'buildings.json').read_text())
    if args.only:
        unknown = set(args.only) - {b['id'] for b in config['buildings']}
        if unknown:
            parser.error('Unknown buildings: ' + ', '.join(sorted(unknown)))
        config['buildings'] = [b for b in config['buildings'] if b['id'] in args.only]
    (work / 'buildings.json').write_text(json.dumps(config))
    helper = work / 'worldmods/workshop_export'
    helper.mkdir(parents=True)
    shutil.copy2(HELPER / 'init.lua', helper / 'init.lua')
    (helper / 'mod.conf').write_text('name = workshop_export\n')
    (work / 'export').mkdir()
    (work / 'capture.conf').write_text('enable_ipv6 = false\nbind_address = 127.0.0.1\nserver_announce = false\n')
    print('Snapshot:', work, flush=True)
    with (work / 'stdout.log').open('w') as log:
        process = subprocess.run([args.engine, '--server', '--world', str(work), '--gameid', 'mineclone2', '--config', str(work / 'capture.conf'), '--port', str(args.port), '--logfile', str(work / 'engine.log')], stdout=log, stderr=subprocess.STDOUT, timeout=180)
    result_file = work / 'export/results.json'
    if process.returncode or not result_file.exists():
        raise SystemExit('Export failed; inspect ' + str(work / 'engine.log'))
    results = json.loads(result_file.read_text())
    entries = {}
    output = ROOT / 'schematics/templates'
    output.mkdir(exist_ok=True)
    previous_path = output / 'manifest.json'
    previous = json.loads(previous_path.read_text()) if previous_path.exists() else {}
    records = {b['id']: b for b in previous.get('buildings', [])} if args.only else {}
    for record in records.values():
        record.setdefault('snapshot_sha256', previous.get('snapshot_sha256'))
    manifest = {'world': str(source), 'snapshot_sha256': snapshot_sha,
                'last_export_buildings': [r['id'] for r in results], 'buildings': []}
    if args.only and previous.get('world'):
        # A selective export (possibly from a scratch world) must not rewrite
        # the top-level provenance; each building record keeps its own hash.
        manifest['world'] = previous['world']
        manifest['snapshot_sha256'] = previous['snapshot_sha256']
    for result in results:
        name = result['id']
        shutil.copy2(work / 'export' / (name + '.mts'), output / (name + '.mts'))
        (output / (name + '.lua')).write_text('-- Generated by tools/workshop_export/export.py.\nreturn ' + lua({'metadata': result['metadata'], 'required_nodes': result['required_nodes']}) + '\n')
        record = {k: v for k, v in result.items() if k not in ('nodes', 'metadata')}
        record['snapshot_sha256'] = snapshot_sha
        records[name] = record
        print(name, result['size'], 'source', result['source_min'], result['source_max'])
    manifest['buildings'] = list(records.values())
    for name, result in records.items():
        entries[name] = {'path': 'schematics/templates/' + name + '.mts', 'size': result['size'],
                         'entrance': result['entrance'], 'entrance_kind': result.get('entrance_kind', 'door'),
                         'data_path': 'schematics/templates/' + name + '.lua'}
        if result.get('ground_offset'):
            entries[name]['ground_offset'] = result['ground_offset']
        if result.get('role'):
            entries[name]['role'] = result['role']
        if result.get('excluded_resident_beds'):
            entries[name]['excluded_resident_beds'] = result['excluded_resident_beds']
    (output / 'catalog.lua').write_text('-- Generated by tools/workshop_export/export.py.\nreturn ' + lua(entries) + '\n')
    (output / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print('Verified', sum(r['verified_nodes'] for r in results), 'nodes; workshop source was read only.')
    if args.validate:
        # Validate this checkout, even when a different towns version is installed.
        validation_mod = work / 'worldmods/towns'
        validation_mod.mkdir()
        for name in ('init.lua', 'mod.conf'):
            shutil.copy2(ROOT / name, validation_mod / name)
        for name in ('src', 'schematics'):
            shutil.copytree(ROOT / name, validation_mod / name)
        shutil.copy2(HELPER / 'validate.lua', helper / 'init.lua')
        (helper / 'mod.conf').write_text('name = workshop_export\ndepends = towns\n')
        with (work / 'world.mt').open('a') as config:
            config.write('\nload_mod_towns = worldmods/towns\n')
        with (work / 'capture.conf').open('a') as config:
            config.write('towns_export_repo = ' + str(validation_mod) + '\n')
        with (work / 'runtime-stdout.log').open('w') as log:
            process = subprocess.run([args.engine, '--server', '--world', str(work), '--gameid', 'mineclone2', '--config', str(work / 'capture.conf'), '--port', str(args.port), '--logfile', str(work / 'runtime.log')], stdout=log, stderr=subprocess.STDOUT, timeout=180)
        report = work / 'runtime-validation.json'
        if process.returncode or not report.exists():
            raise SystemExit('Runtime checks failed; inspect ' + str(work / 'runtime.log'))
        manifest['runtime_validation'] = json.loads(report.read_text())
        (output / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
        print('Runtime checks:', manifest['runtime_validation'])


if __name__ == '__main__':
    main()
